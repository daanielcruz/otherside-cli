export function pickVerbForTurn(seed: number): string {
  const hash = Math.abs(Math.sin((seed + 1) * 23.456 + 12.345)) * 43758.5453;
  const randomIndex = Math.floor((hash - Math.floor(hash)) * VERBS.length);
  return VERBS[randomIndex] ?? "Drifting";
}

